// Copies the question bank and brand logos out of the web app (../index.html) so the
// extension uses identical content. Re-run after editing QBANK in index.html.
import {readFileSync, writeFileSync, mkdirSync} from 'node:fs';
import vm from 'node:vm';

const html = readFileSync(new URL('../../index.html', import.meta.url), 'utf8');
const outDir = new URL('../frontend/lib/data/', import.meta.url);

function arrayLiteralAfter(source, marker) {
  const start = source.indexOf(marker);
  if (start < 0) throw new Error(`Marker not found: ${marker}`);
  const open = source.indexOf('[', start);
  const close = source.indexOf('\n];', open);
  if (close < 0) throw new Error(`End of array not found after: ${marker}`);
  return source.slice(open, close + 2);
}

function logo(name) {
  const match = html.match(new RegExp(`const ${name}_B64 = '([A-Za-z0-9+/=]+)'`));
  if (!match) throw new Error(`Logo not found: ${name}`);
  return match[1];
}

const qbank = vm.runInNewContext(arrayLiteralAfter(html, 'const QBANK = ['));
const logos = {
  columbia: {base64: logo('COLUMBIA'), width: 140, height: 35},
  sorel: {base64: logo('SOREL'), width: 160, height: 40},
  mountainhardwear: {base64: logo('MHW'), width: 200, height: 45},
  prana: {base64: logo('PRANA'), width: 160, height: 40},
};

const header = '// GENERATED by scripts/extract-web-app-data.mjs from ../index.html. Do not edit.\n';
mkdirSync(outDir, {recursive: true});
writeFileSync(new URL('questionBank.data.js', outDir), `${header}export const QBANK = ${JSON.stringify(qbank, null, 2)};\n`);
writeFileSync(new URL('logos.data.js', outDir), `${header}export const LOGOS = ${JSON.stringify(logos)};\n`);
process.stdout.write(`Wrote ${qbank.length} questions and ${Object.keys(logos).length} logos.\n`);
