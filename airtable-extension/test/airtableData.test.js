import {describe, it, expect} from 'vitest';
import {
  readRequisition, readGuide, newGuideFields, savePicksFields, generatedFields, ROUNDS,
} from '../frontend/lib/airtableData.js';

function fakeRecord(id, values, createdTime = new Date('2026-10-01T00:00:00Z')) {
  return {
    id,
    createdTime,
    getCellValue: (name) => values[name] ?? null,
    getCellValueAsString: (name) => {
      const v = values[name];
      if (v == null) return '';
      if (typeof v === 'object' && 'name' in v) return v.name;
      return String(v);
    },
  };
}

describe('airtableData', () => {
  it('reads a requisition', () => {
    const rec = fakeRecord('rec1', {
      'Position Title': 'Sr PM', 'Req #': 'R-100', Brand: {name: 'SOREL'},
      'Hiring Manager': {name: 'Jamie Lee'}, 'Panel Interview Format': {name: 'In-Person'},
      '#of Panelists': 3,
    });
    expect(readRequisition(rec)).toEqual({
      id: 'rec1', positionTitle: 'Sr PM', reqNumber: 'R-100', brand: 'SOREL',
      hiringManager: 'Jamie Lee', format: 'In-Person', panelistCount: 3,
    });
  });

  it('treats a missing panelist count as 0', () => {
    expect(readRequisition(fakeRecord('rec1', {})).panelistCount).toBe(0);
  });

  it('reads a guide', () => {
    const rec = fakeRecord('recG', {
      'Guide Name': 'Sr PM – Panel', Requisition: [{id: 'rec1', name: 'Sr PM'}],
      'Interview Round': {name: 'Panel'}, Panelists: 'A\nB', Selections: '{"v":1}',
      'Guide File': [{id: 'att1', url: 'u', filename: 'f.docx'}], 'Last Generated': '2026-10-14',
    });
    expect(readGuide(rec)).toEqual({
      id: 'recG', name: 'Sr PM – Panel', requisitionId: 'rec1', round: 'Panel',
      panelistsText: 'A\nB', selectionsText: '{"v":1}',
      files: [{id: 'att1', url: 'u', filename: 'f.docx'}], lastGenerated: '2026-10-14',
      createdTime: Date.parse('2026-10-01T00:00:00Z'),
    });
  });

  it('reads an unlinked, empty guide', () => {
    const g = readGuide(fakeRecord('recG', {}));
    expect(g.requisitionId).toBeNull();
    expect(g.files).toEqual([]);
    expect(g.round).toBe('');
  });

  it('builds field maps for writes', () => {
    expect(ROUNDS).toEqual(['Panel', 'Second Panel', 'Final', 'Other']);
    expect(newGuideFields({name: 'N', requisitionId: 'rec1', round: 'Final'})).toEqual({
      'Guide Name': 'N', Requisition: [{id: 'rec1'}], 'Interview Round': {name: 'Final'},
    });
    expect(savePicksFields({panelistsText: 'A', selectionsText: '{}'})).toEqual({
      Panelists: 'A', Selections: '{}',
    });
    const at = new Date('2026-10-14T12:00:00Z');
    expect(generatedFields({files: [{url: 'u', filename: 'f'}], userId: 'usr1', at})).toEqual({
      'Guide File': [{url: 'u', filename: 'f'}], 'Last Generated': at.toISOString(),
      'Generated By': {id: 'usr1'},
    });
  });
});
