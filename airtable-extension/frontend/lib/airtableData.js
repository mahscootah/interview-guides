export const TABLES = {requisitions: 'Master Tracker - All TA', guides: 'Interview Guides'};

export const REQ_FIELDS = {
  positionTitle: 'Position Title',
  reqNumber: 'Req #',
  brand: 'Brand',
  hiringManager: 'Hiring Manager',
  format: 'Panel Interview Format',
  panelistCount: '#of Panelists',
};

export const GUIDE_FIELDS = {
  name: 'Guide Name',
  requisition: 'Requisition',
  round: 'Interview Round',
  panelists: 'Panelists',
  selections: 'Selections',
  file: 'Guide File',
  lastGenerated: 'Last Generated',
  generatedBy: 'Generated By',
};

export const ROUNDS = ['Panel', 'Second Panel', 'Final', 'Other'];

export function readRequisition(record) {
  const text = (name) => record.getCellValueAsString(name).trim();
  return {
    id: record.id,
    positionTitle: text(REQ_FIELDS.positionTitle),
    reqNumber: text(REQ_FIELDS.reqNumber),
    brand: text(REQ_FIELDS.brand),
    hiringManager: text(REQ_FIELDS.hiringManager),
    format: text(REQ_FIELDS.format),
    panelistCount: Number(record.getCellValue(REQ_FIELDS.panelistCount)) || 0,
  };
}

export function readGuide(record) {
  const links = record.getCellValue(GUIDE_FIELDS.requisition) ?? [];
  return {
    id: record.id,
    name: record.getCellValueAsString(GUIDE_FIELDS.name),
    requisitionId: links[0]?.id ?? null,
    round: record.getCellValue(GUIDE_FIELDS.round)?.name ?? '',
    panelistsText: record.getCellValueAsString(GUIDE_FIELDS.panelists),
    selectionsText: record.getCellValueAsString(GUIDE_FIELDS.selections),
    files: record.getCellValue(GUIDE_FIELDS.file) ?? [],
    lastGenerated: record.getCellValueAsString(GUIDE_FIELDS.lastGenerated),
    createdTime: record.createdTime ? new Date(record.createdTime).getTime() : 0,
  };
}

export function newGuideFields({name, requisitionId, round}) {
  return {
    [GUIDE_FIELDS.name]: name,
    [GUIDE_FIELDS.requisition]: [{id: requisitionId}],
    [GUIDE_FIELDS.round]: {name: round},
  };
}

export function savePicksFields({panelistsText, selectionsText}) {
  return {[GUIDE_FIELDS.panelists]: panelistsText, [GUIDE_FIELDS.selections]: selectionsText};
}

export function generatedFields({files, userId, at}) {
  return {
    [GUIDE_FIELDS.file]: files,
    [GUIDE_FIELDS.lastGenerated]: at.toISOString(),
    [GUIDE_FIELDS.generatedBy]: {id: userId},
  };
}
